/**
 * Enum that defines various font sizes used throughout the application.
 * The values are specified in either pixels (px) or rem units.
 * 
 * @enum {string}
 */
export enum FontSizesEnum {
    /**
     * Font size of 32px, used for prominent titles or large headings.
     * @type {string}
     */
    Eta = "32px",

    /**
     * Font size of 30px, used for large titles or important subtitles.
     * @type {string}
     */
    Lota = "30px",

    /**
     * Font size of 24px, used for subtitles or medium header text.
     * @type {string}
     */
    Lambda = '24px',

    /**
     * Font size of 20px, used for main titles or secondary text.
     * @type {string}
     */
    Alpha = "20px",

    /**
     * Font size of 18px, used for smaller headings or body text.
     * @type {string}
     */
    Beta = "18px",

    /**
     * Font size of 16px, typically used for body text or captions.
     * @type {string}
     */
    Gamma = "16px",

    /**
     * Font size of 15px, used for regular text in a more flexible unit.
     * @type {string}
     */
    Omicron = "15px",

    /**
     * Font size of 14px, used for small text or less important details.
     * @type {string}
     */
    Delta = "14px",

    /**
     * Font size of 13px, used for slightly smaller text or fine details.
     * @type {string}
     */
    Theta = "13px",

    /**
     * Font size of 12px, used for fine print or minimal text.
     * @type {string}
     */
    Epsilon = "12px",

    /**
     * Font size of 11px, used for very small text or disclaimers.
     * @type {string}
     */
    Omega = "11px",

    /**
     * Font size of 10px, used for regular text in a more flexible unit.
     * @type {string}
     */
    Zeta = "10px",

    /**
     * Font size of 9px, used for extra small text or fine print.
     * @type {string}
     */
    Sigma = "9px",

    /**
     * Font size of 0.8rem, used for small text in a more flexible unit.
     * @type {string}
     */
    kappa = "0.8rem",

    /**
     * Font size of 1rem, used for small text in a more flexible unit.
     * @type {string}
     */
    Upsilon = "1rem",
}
